#!/usr/bin/env python3
"""The list screens of shared/screens as code for each platform: variant В of docs/ui/platforms.md, on trial against
screens made by hand (docs/research/list-screens-probe.md).

  gen_screens.py            write the generated files
  gen_screens.py --check    exit 1 if one of them is not what the descriptions give (CI)

  app/src/main/java/io/niko/ui/settings/ListScreens.kt    Android: each screen as a ListSpec (ui/settings/ListScreen.kt)
  desktop/lib/gen/screens.g.dart                           the window: each screen as a ListSpec
                                                           (lib/settings/list_screen.dart), and the texts they name

A description, shared/screens/<screen>.json:

  screen    its name, snake_case; the generated value is its camelCase
  canvas    the artboard it is drawn from
  title     the top bar's name, back the way back's label: names of Android's strings (res/values/strings.xml)
  rows      the page top to bottom, each one of
              {"kind": "fields", "fields": [FIELD, ...]}               fields side by side (m-fields-row)
              {"kind": "field", FIELD's attributes}                    one field across the page (m-field)
              {"kind": "group", "rows": [ITEM, ...]}                   rows in a group (m-list)
              {"kind": "section", "title": STRING, "rows": [ITEM, ...]}  rows under an overline (m-section)
  FIELD     key; label, a string; input text (the default), port or secret; mono and narrow, true or false;
            action {"id", "icon": a Lucide name in shared/icons/lucide, "label": a string}
  ITEM      {"kind": "switch", "key", "title": a string, "enabledBy": the key of a switch on the same screen}
            {"kind": "link", "id", "title": a string}: a row that opens something, the host's summary of it at its
            end and a chevron; pressed, the host gets its id

A key is the setting's key in the settings store (io.niko.Key). Any row, field or item may say "only": "android" or
"desktop", and the other platform leaves it out. An attribute not named here fails the tool: the language stays as
small as the screens need. The window's texts are Android's, copied for the languages the window speaks (en, ru).
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "shared", "screens")
KOTLIN = "app/src/main/java/io/niko/ui/settings/ListScreens.kt"
DART = "desktop/lib/gen/screens.g.dart"
STRINGS = {"en": "app/src/main/res/values/strings.xml", "ru": "app/src/main/res/values-ru/strings.xml"}
ICONS = "shared/icons/lucide"
GEN_ICONS = "shared/tool/gen_icons.py"
HEADER = "GENERATED by shared/tool/gen_screens.py from shared/screens. Do not edit: change the description and run the tool."

PLATFORMS = ("android", "desktop")
INPUTS = ("text", "port", "secret")
SCREEN = {"screen", "canvas", "title", "back", "rows"}
LINES = {
    "fields": {"kind", "fields", "only"},
    "field": {"kind", "key", "label", "input", "mono", "narrow", "action", "only"},
    "group": {"kind", "rows", "only"},
    "section": {"kind", "title", "rows", "only"},
}
FIELD = {"key", "label", "input", "mono", "narrow", "action", "only"}
ACTION = {"id", "icon", "label"}
ITEMS = {"switch": {"kind", "key", "title", "enabledBy", "only"}, "link": {"kind", "id", "title", "only"}}


class Invalid(Exception):
    pass


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(part.capitalize() for part in rest)


def strings(lang):
    """Android's strings of one language, by name, as the app shows them (its escapes undone)."""
    texts = {}
    for node in ET.parse(os.path.join(ROOT, STRINGS[lang])).getroot().iter("string"):
        text = "".join(node.itertext())
        texts[node.get("name")] = re.sub(r"\\(['\"@?\\])", r"\1", text).replace("\\n", "\n")
    return texts


def window_icons():
    """The window's names of its icons by their SVG's (gen_icons.py's WINDOW): a screen's icon must be one of them."""
    text = open(os.path.join(ROOT, GEN_ICONS), encoding="utf-8").read()
    block = re.search(r"^WINDOW = \{(.*?)^\}", text, re.S | re.M).group(1)
    return {svg: name for name, svg in re.findall(r'"(\w+)": "([\w-]+)"', block)}


def check_attrs(where, node, allowed):
    if not isinstance(node, dict):
        raise Invalid(f"{where}: not an object")
    unknown = set(node) - allowed
    if unknown:
        raise Invalid(f"{where}: {', '.join(sorted(unknown))} not in the language")
    only = node.get("only")
    if only is not None and only not in PLATFORMS:
        raise Invalid(f"{where}: only {only!r}, not one of {', '.join(PLATFORMS)}")


def check_string(where, name, texts):
    if not isinstance(name, str) or name not in texts["en"]:
        raise Invalid(f"{where}: string {name!r} is not in {STRINGS['en']}")


def check_key(where, key):
    if not isinstance(key, str) or not re.fullmatch(r"[a-z][A-Za-z0-9]*", key):
        raise Invalid(f"{where}: key {key!r} is not a settings key")


def check_field(where, field, texts, icons):
    check_attrs(where, field, FIELD | {"kind"})
    check_key(where, field.get("key"))
    check_string(where, field.get("label"), texts)
    if field.get("input", "text") not in INPUTS:
        raise Invalid(f"{where}: input {field['input']!r}, not one of {', '.join(INPUTS)}")
    for flag in ("mono", "narrow"):
        if not isinstance(field.get(flag, False), bool):
            raise Invalid(f"{where}: {flag} is not true or false")
    action = field.get("action")
    if action is not None:
        check_attrs(f"{where}, action", action, ACTION)
        if not re.fullmatch(r"[a-z][A-Za-z0-9]*", str(action.get("id"))):
            raise Invalid(f"{where}: action id {action.get('id')!r}")
        if not os.path.exists(os.path.join(ROOT, ICONS, f"{action.get('icon')}.svg")):
            raise Invalid(f"{where}: icon {action.get('icon')!r} is not in {ICONS}")
        if action["icon"] not in icons:
            raise Invalid(f"{where}: icon {action['icon']!r} is not one of the window's (WINDOW in {GEN_ICONS})")
        check_string(f"{where}, action", action.get("label"), texts)


def load(path, texts, icons):
    where = os.path.relpath(path, ROOT)
    screen = json.load(open(path, encoding="utf-8"))
    check_attrs(where, screen, SCREEN)
    if screen.get("screen") != os.path.basename(path)[:-5] or not re.fullmatch(r"[a-z][a-z0-9_]*", screen["screen"]):
        raise Invalid(f"{where}: screen {screen.get('screen')!r} is not the file's name")
    for name in ("title", "back"):
        check_string(where, screen.get(name), texts)
    switches = set()
    wanted = []
    for i, line in enumerate(screen.get("rows") or []):
        at = f"{where}, row {i + 1}"
        kind = line.get("kind") if isinstance(line, dict) else None
        if kind not in LINES:
            raise Invalid(f"{at}: kind {kind!r}, not one of {', '.join(LINES)}")
        check_attrs(at, line, LINES[kind])
        if kind == "fields":
            if not line.get("fields"):
                raise Invalid(f"{at}: no fields")
            for j, field in enumerate(line["fields"]):
                check_field(f"{at}, field {j + 1}", field, texts, icons)
        elif kind == "field":
            check_field(at, line, texts, icons)
        else:
            if kind == "section":
                check_string(at, line.get("title"), texts)
            if not line.get("rows"):
                raise Invalid(f"{at}: no rows")
            for j, item in enumerate(line["rows"]):
                item_at = f"{at}, item {j + 1}"
                item_kind = item.get("kind") if isinstance(item, dict) else None
                if item_kind not in ITEMS:
                    raise Invalid(f"{item_at}: kind {item_kind!r}, not one of {', '.join(ITEMS)}")
                check_attrs(item_at, item, ITEMS[item_kind])
                check_string(item_at, item.get("title"), texts)
                if item_kind == "link":
                    if not re.fullmatch(r"[a-z][A-Za-z0-9]*", str(item.get("id"))):
                        raise Invalid(f"{item_at}: id {item.get('id')!r}")
                    continue
                check_key(item_at, item.get("key"))
                switches.add(item["key"])
                if "enabledBy" in item:
                    wanted.append((item_at, item["enabledBy"]))
    if not screen.get("rows"):
        raise Invalid(f"{where}: no rows")
    for at, key in wanted:
        if key not in switches:
            raise Invalid(f"{at}: enabledBy {key!r} is no switch of the screen")
    return screen


def kept(nodes, platform):
    return [node for node in nodes if node.get("only", platform) == platform]


def used_strings(screen):
    names = [screen["title"], screen["back"]]
    for line in screen["rows"]:
        for field in line.get("fields", [line] if line["kind"] == "field" else []):
            names.append(field["label"])
            if "action" in field:
                names.append(field["action"]["label"])
        if line["kind"] == "section":
            names.append(line["title"])
        names += [item["title"] for item in line.get("rows", [])]
    return names


def kotlin_field(field):
    args = [f'"{field["key"]}"', f"R.string.{field['label']}"]
    if field.get("input", "text") != "text":
        args.append(f"input = FieldInput.{field['input'].upper()}")
    for flag in ("mono", "narrow"):
        if field.get(flag):
            args.append(f"{flag} = true")
    action = field.get("action")
    if action:
        icon = "ic_l_" + action["icon"].replace("-", "_")
        args.append(f'action = FieldAction("{action["id"]}", R.drawable.{icon}, R.string.{action["label"]})')
    return f"FieldSpec({', '.join(args)})"


def kotlin_item(item):
    if item["kind"] == "link":
        return f'LinkItem("{item["id"]}", R.string.{item["title"]})'
    args = [f'"{item["key"]}"', f"R.string.{item['title']}"]
    if "enabledBy" in item:
        args.append(f'enabledBy = "{item["enabledBy"]}"')
    return f"SwitchItem({', '.join(args)})"


def kotlin(screens):
    out = [f"// {HEADER}", "package io.niko.ui.settings", "", "import io.niko.R", "",
           "/** The list screens of shared/screens, as the phone draws them (ListScreen). */", "object ListScreens {"]
    for name, screen in screens:
        out.append(f"    /** {name}.json: {screen['canvas']} */")
        out.append(f"    val {camel(screen['screen'])} = ListSpec(")
        out.append(f"        R.string.{screen['title']},")
        out.append(f"        R.string.{screen['back']},")
        out.append("        listOf(")
        for line in kept(screen["rows"], "android"):
            kind = line["kind"]
            if kind == "fields":
                out.append("            FieldsLine(")
                out.append("                listOf(")
                out += [f"                    {kotlin_field(f)}," for f in kept(line["fields"], "android")]
                out.append("                ),")
                out.append("            ),")
            elif kind == "field":
                out.append(f"            FieldLine({kotlin_field(line)}),")
            else:
                out.append("            SectionLine(" if kind == "section" else "            GroupLine(")
                if kind == "section":
                    out.append(f"                R.string.{line['title']},")
                out.append("                listOf(")
                out += [f"                    {kotlin_item(i)}," for i in kept(line["rows"], "android")]
                out.append("                ),")
                out.append("            ),")
        out.append("        ),")
        out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"


def dart_string(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def dart_field(field, icons):
    args = [dart_string(field["key"]), dart_string(field["label"])]
    if field.get("input", "text") != "text":
        args.append(f"input: FieldInput.{field['input']}")
    for flag in ("mono", "narrow"):
        if field.get(flag):
            args.append(f"{flag}: true")
    action = field.get("action")
    if action:
        args.append(f"action: FieldAction({dart_string(action['id'])}, NikoIcons.{icons[action['icon']]}, "
                    f"{dart_string(action['label'])})")
    return f"FieldSpec({', '.join(args)})"


def dart_item(item):
    if item["kind"] == "link":
        return f"LinkItem({dart_string(item['id'])}, {dart_string(item['title'])})"
    args = [dart_string(item["key"]), dart_string(item["title"])]
    if "enabledBy" in item:
        args.append(f"enabledBy: {dart_string(item['enabledBy'])}")
    return f"SwitchItem({', '.join(args)})"


def dart(screens, texts, icons):
    out = [f"// {HEADER}", "", "import '../settings/list_spec.dart';", "import '../ui/icons.dart';", "",
           "/// The list screens of shared/screens, as the window draws them (ListScreen).", "abstract final class ListScreens {"]
    names = []
    for name, screen in screens:
        if names:
            out.append("")
        out.append(f"  /// {name}.json: {screen['canvas']}")
        out.append(f"  static const {camel(screen['screen'])} = ListSpec(")
        out.append(f"    title: {dart_string(screen['title'])},")
        out.append(f"    back: {dart_string(screen['back'])},")
        out.append("    lines: [")
        for line in kept(screen["rows"], "desktop"):
            kind = line["kind"]
            if kind == "fields":
                out.append("      FieldsLine([")
                out += [f"        {dart_field(f, icons)}," for f in kept(line["fields"], "desktop")]
                out.append("      ]),")
            elif kind == "field":
                out.append(f"      FieldLine({dart_field(line, icons)}),")
            else:
                head = f"SectionLine({dart_string(line['title'])}, [" if kind == "section" else "GroupLine(["
                out.append(f"      {head}")
                out += [f"        {dart_item(i)}," for i in kept(line["rows"], "desktop")]
                out.append("      ]),")
        out.append("    ],")
        out.append("  );")
        names += used_strings({**screen, "rows": [
            {**line, **({"fields": kept(line["fields"], "desktop")} if "fields" in line else {}),
             **({"rows": kept(line["rows"], "desktop")} if "rows" in line else {})}
            for line in kept(screen["rows"], "desktop")]})
    out.append("}")
    out.append("")
    out.append("/// The texts the screens name, by language: Android's strings of the same names.")
    out.append("const screenTexts = <String, Map<String, String>>{")
    for lang in STRINGS:
        out.append(f"  '{lang}': {{")
        for name in sorted(set(names)):
            text = texts[lang].get(name, texts["en"][name])
            out.append(f"    {dart_string(name)}: {dart_string(text)},")
        out.append("  },")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    texts = {lang: strings(lang) for lang in STRINGS}
    icons = window_icons()
    screens = []
    try:
        for file in sorted(os.listdir(SOURCE)):
            if file.endswith(".json"):
                screens.append((file[:-5], load(os.path.join(SOURCE, file), texts, icons)))
    except (Invalid, json.JSONDecodeError) as e:
        print(f"gen_screens: {e}", file=sys.stderr)
        return 1
    stale = 0
    for path, text in ((KOTLIN, kotlin(screens)), (DART, dart(screens, texts, icons))):
        full = os.path.join(ROOT, path)
        if check:
            if not os.path.exists(full) or open(full, encoding="utf-8").read() != text:
                print(f"{path} is not what shared/screens gives: run shared/tool/gen_screens.py")
                stale = 1
        else:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            open(full, "w", encoding="utf-8").write(text)
    return stale


if __name__ == "__main__":
    sys.exit(main())
